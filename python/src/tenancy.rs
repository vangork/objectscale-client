#[derive(Clone, Debug, Default, Serialize)]
#[pyclass(get_all)]
pub(crate) struct UserMapping {
    // A single-valued attribute indicating the user's IDP domain
    #[pyo3(set)]
    domain: String,
    // Attributes
    #[pyo3(set)]
    attributes: Vec<Attribute>,
    // Groups
    #[pyo3(set)]
    groups: Vec<String>,
}

impl From<tenancy::UserMapping> for UserMapping {
    fn from(user_mapping: tenancy::UserMapping) -> Self {
        Self {
            domain: user_mapping.domain,
            attributes: user_mapping
                .attributes
                .into_iter()
                .map(Attribute::from)
                .collect(),
            groups: user_mapping.groups,
        }
    }
}

impl From<UserMapping> for tenancy::UserMapping {
    fn from(user_mapping: UserMapping) -> Self {
        Self {
            domain: user_mapping.domain,
            attributes: user_mapping
                .attributes
                .into_iter()
                .map(tenancy::Attribute::from)
                .collect(),
            groups: user_mapping.groups,
        }
    }
}

#[pymethods]
impl UserMapping {
    #[new]
    fn new() -> Self {
        Self::default()
    }

    fn __str__(&self) -> String {
        format!("{}", serde_json::to_string(self).unwrap())
    }
}
