//! Define the replication details.
//!
use crate::client::{ManagementClient, AUTH_HEADER_KEY};
use crate::response::get_content_text;
use anyhow::{Context as _, Result};
use derive_builder::Builder;
use reqwest::header::ACCEPT;
use serde::{Deserialize, Serialize};
use serde_aux::field_attributes::deserialize_default_from_null;

#[derive(Clone, Default, Debug, Deserialize, PartialEq, Eq, Serialize)]
pub struct VarrayMapping {
    pub name: String,
    pub value: String,
    pub is_replication_target: bool,
}

/// Storage pool is a logical construct that contains physical nodes.
#[derive(Builder, Clone, Debug, Default, Deserialize, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ReplicationGroup {
    /// Indicates whether the resource is global.
    #[serde(deserialize_with = "deserialize_default_from_null")]
    pub global: bool,
    /// Indicates whether the resource is remote.
    #[serde(deserialize_with = "deserialize_default_from_null")]
    pub remote: bool,
    // TODO:
    // #[serde(deserialize_with = "deserialize_default_from_null")]
    // pub vdc: String,
    /// Varray mappings
    pub varray_mappings: Vec<VarrayMapping>,
    /// Unique name identifying this classification of replication group
    pub name: String,
    /// Identifier that is generated by ECS when the resource is created. The resource Id is guaranteed to be unique and immutable across all virtual data centers for all time.
    pub id: String,
    // TODO:
    // Hyperlink to the details for this resource
    // pub link: Link,
    /// Timestamp that shows when this resource was created in ECS
    #[serde(rename = "creation_time")]
    pub creation_time: i64,
    /// Indicates whether the resource is inactive. When a user removes a resource, the resource is put in this state before it is removed from the ECS database.
    pub inactive: bool,
    /// Indicated whether the resource is an internal resource
    #[serde(deserialize_with = "deserialize_default_from_null")]
    pub internal: bool,
    /// Description of the replication group
    pub description: String,
    /// Parameter to check if the Vpool can access all Namespace
    pub is_allow_all_namespaces: bool,
    /// Parameter to check if the rebalancing is enabled
    #[serde(rename = "enable_rebalancing")]
    pub enable_rebalancing: bool,
    /// Parameter to check if to use replication targets
    pub use_replication_target: bool,
    /// Parameter to check for full replication
    pub is_full_rep: bool,
}

#[derive(Deserialize)]
struct ReplicationGroupList {
    data_service_vpool: Vec<ReplicationGroup>,
}

impl ReplicationGroup {
    pub(crate) fn get(client: &mut ManagementClient, id: &str) -> Result<Self> {
        let request_url = format!("{}vdc/data-service/vpools/{}", client.endpoint, id);
        let resp = client
            .http_client
            .get(request_url)
            .header(ACCEPT, "application/json")
            .header(AUTH_HEADER_KEY, client.access_token.as_ref().unwrap())
            .send()?;
        let text = get_content_text(resp).with_context(|| "Failed to get replication group")?;
        let resp: Self = serde_json::from_str(&text).with_context(|| {
            format!(
                "Unable to deserialise ReplicationGroup. Body was: \"{}\"",
                text
            )
        })?;
        Ok(resp)
    }

    pub(crate) fn list(client: &mut ManagementClient) -> Result<Vec<Self>> {
        let request_url = format!("{}vdc/data-service/vpools", client.endpoint);
        let resp = client
            .http_client
            .get(request_url)
            .header(ACCEPT, "application/json")
            .header(AUTH_HEADER_KEY, client.access_token.as_ref().unwrap())
            .send()?;
        let text = get_content_text(resp).with_context(|| "Failed to list replication groups")?;
        let resp: ReplicationGroupList = serde_json::from_str(&text).with_context(|| {
            format!(
                "Unable to deserialise ReplicationGroupList. Body was: \"{}\"",
                text
            )
        })?;
        Ok(resp.data_service_vpool)
    }
}
